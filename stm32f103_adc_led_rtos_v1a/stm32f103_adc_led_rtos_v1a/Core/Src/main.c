/* USER CODE BEGIN 4 */
void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef* hadc)
{
  if(hadc->Instance == ADC1)
  {
    HAL_ADC_Stop_DMA(hadc);

    // Give the semaphore to unblock vDataProcessingTask.
    // CMSIS-OS v1 API handles context switching internally, so it's simpler.
    osSemaphoreRelease(xAdcSemaphoreHandle);
  }
}
