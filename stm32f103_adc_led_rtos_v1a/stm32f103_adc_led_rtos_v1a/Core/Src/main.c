/**
  * @brief  Function implementing the vDataProcessing thread.
  * @param  argument: Not used
  * @retval None
  */
/* USER CODE END Header_vDataProcessingTask */
void vDataProcessingTask(void const * argument)
{
  /* USER CODE BEGIN 5 */
	(void)argument;
	  // Start the first ADC/DMA conversion
	  HAL_ADC_Start_DMA(&hadc1, (uint32_t*)adc_buffer, N);
  /* Infinite loop */
  for(;;)
  {
	  // Wait for the semaphore from the ADC/DMA completion ISR
	  if (osSemaphoreWait(xAdcSemaphoreHandle, osWaitForever) == osOK)
	      {
	        // --- Process the data ---
	        uint32_t temp = 0;
	        for (uint16_t i = 0; i < N; i++)
	        {
	          temp += adc_buffer[i];
	        }
	        uint16_t output = (uint16_t)(temp / N);
	        // --- Send the result to the display task ---
	        // osMessagePut will overwrite if the queue (mailbox) is full
	        osMessagePut(xDisplayQueueHandle, (uint32_t)output, 0);

	        // --- Restart ADC/DMA for the next cycle ---
	        HAL_Delay(1); // Using HAL_Delay is safe because timebase is now a TIM
	        HAL_ADC_Start_DMA(&hadc1, (uint32_t*)adc_buffer, N);
	      }

  }
  /* USER CODE END 5 */
}

/* USER CODE BEGIN Header_vDisplayTask */
/**
* @brief Function implementing the vDisplay thread.
* @param argument: Not used
* @retval None
*/
/* USER CODE END Header_vDisplayTask */
void vDisplayTask(void const * argument)
{
  /* USER CODE BEGIN vDisplayTask */
	  (void)argument;
	  uint16_t displayValue = 0;
	  osEvent evt;
  /* Infinite loop */
  for(;;)
  {
	  // Check for a new value from the queue without blocking
	      evt = osMessageGet(xDisplayQueueHandle, 0);
	      if (evt.status == osEventMessage)
	      {
	        // New value received, update local variable
	        displayValue = (uint16_t)evt.value.v;
	      }

	      // Call the display function continuously
	      Display_7_SEG(displayValue);

	      // Delay to control the refresh rate of the display
	      osDelay(5); // osDelay takes milliseconds
  }
  /* USER CODE END vDisplayTask */
}

